// Package ids validates identifiers that arrive from clients.
package ids

// IsUUID reports whether s is a canonical UUID (8-4-4-4-12 hex digits).
// Handlers check IDs before querying so malformed values never reach
// PostgreSQL, which would reject them with an error.
func IsUUID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if i == 8 || i == 13 || i == 18 || i == 23 {
			if c != '-' {
				return false
			}
			continue
		}
		if !('0' <= c && c <= '9' || 'a' <= c && c <= 'f' || 'A' <= c && c <= 'F') {
			return false
		}
	}
	return true
}
